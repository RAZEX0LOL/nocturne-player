import { chromium } from 'playwright-core'
import assert from 'node:assert/strict'
const executablePath = process.env.CHROME ?? `${process.env.HOME}/Library/Caches/ms-playwright/chromium-1228/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing`
const browser = await chromium.launch({ executablePath, args: ['--autoplay-policy=no-user-gesture-required'] })
const page = await browser.newPage({ viewport: { width: 1360, height: 900 }, locale: 'ru-RU' })
await page.addInitScript(() => Object.defineProperty(navigator, 'clipboard', { value: { writeText: async (value) => { window.__copiedDiagnostics = value } } }))
const errors = []
page.on('pageerror', (e) => errors.push(e.message))
try {
 await page.goto('http://localhost:1431/')
 await page.locator('input').nth(0).fill('http://127.0.0.1:4533')
 await page.locator('input').nth(1).fill('test')
 await page.locator('input').nth(2).fill('demo')
 await page.locator('button[type=submit]').click()
 await page.locator('nav button', { hasText: 'Альбомы' }).click()
 await page.locator('main .group > button').first().click()
 const rows = page.locator('main .song-row')
 await page.waitForFunction(() => document.querySelectorAll('main .song-row').length === 3)
 const filter = page.getByRole('textbox', { name: 'Поиск в списке' })
 await filter.fill('ТРЕК 3')
 await page.waitForFunction(() => document.querySelectorAll('main .song-row').length === 1)
 assert.match(await rows.first().innerText(), /Тестовый трек 3/)
 await rows.first().dblclick()
 await page.waitForFunction(() => document.querySelector('footer')?.textContent.includes('Тестовый трек 3'))
 await filter.fill('')
 await page.getByRole('combobox', { name: 'Порядок треков' }).selectOption('created:true')
 assert.match(await rows.first().innerText(), /Тестовый трек 3/)
 await rows.first().click()
 await rows.last().click({ modifiers: ['Shift'] })
 assert.equal(await page.locator('main .song-row[aria-selected=true]').count(), 3)
 await rows.first().click({ button: 'right' })
 await page.evaluate(() => window.__lastMenu.find((v) => v && v.text === 'Информация о треке')?.action())
 // Для группы информация недоступна; открываем меню одного трека.
 await rows.first().click()
 await rows.first().click({ button: 'right' })
 await page.evaluate(() => window.__lastMenu.find((v) => v && v.text === 'Информация о треке').action())
 await page.getByRole('dialog', { name: 'Информация о треке' }).waitFor()
 assert.match(await page.getByRole('dialog').innerText(), /WAV/)
 assert.match(await page.getByRole('dialog').innerText(), /22050 Hz/)
 await page.getByRole('button', { name: 'Скопировать диагностику', exact: true }).click()
 const diagnostics = await page.evaluate(() => window.__copiedDiagnostics)
 assert.equal(JSON.parse(diagnostics).originalFormat, 'wav')
 assert.equal(JSON.parse(diagnostics).title, 'Тестовый трек 3')
 assert(!/127\.0\.0\.1|demo|password|token|https?:|[?&][uts]=/i.test(diagnostics))
 await page.screenshot({ path: '../build/track-tools/desktop-information.png' })
 await page.getByRole('button', { name: 'Готово', exact: true }).click()
 await filter.fill('нет такого трека')
 assert.equal(await rows.count(), 0)
 await page.getByRole('button', { name: 'Текущий трек', exact: true }).click()
 assert.equal(await filter.inputValue(), '')
 await page.waitForFunction(() => document.querySelectorAll('main .song-row[aria-selected=true]').length === 1)
 assert.match(await page.locator('main .song-row[aria-selected=true]').innerText(), /Тестовый трек 3/)
 await page.screenshot({ path: '../build/track-tools/desktop-album-tools.png' })
 assert.deepEqual(errors, [])
 console.log('PASS: album filter, newest order, visible playback, selection, track information, current track reveal; no runtime errors')
} finally { await browser.close() }
